_REMOTE_NOTES_CACHE: dict[str, Any] = {"at": 0.0, "data": None, "ok": False, "channel": ""}
_REMOTE_NOTES_TTL_OK = 300.0
_REMOTE_NOTES_TTL_FAIL = 30.0


def clear_remote_notes_cache() -> None:
    _REMOTE_NOTES_CACHE.update({"at": 0.0, "data": None, "ok": False, "channel": ""})


def notes_for_version(version: str | None, source: dict[str, list[str]] | None = None) -> list[str]:
    if not version:
        return []
    key = str(version).strip().lstrip("vV")
    table = source if source is not None else RELEASE_NOTES_FA
    return list(table.get(key) or [])


def latest_notes_block(source: dict[str, list[str]] | None = None) -> dict[str, object] | None:
    table = source if source is not None else RELEASE_NOTES_FA
    for ver, notes in table.items():
        if notes:
            return {"version": ver, "notes": list(notes)}
    return None


def parse_release_notes_source(src: str) -> dict[str, list[str]]:
    """Extract RELEASE_NOTES_FA dict from release_notes.py source text."""
    tree = ast.parse(src)
    value_node = None
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "RELEASE_NOTES_FA":
                    value_node = node.value
                    break
        elif isinstance(node, ast.AnnAssign):
            target = node.target
            if isinstance(target, ast.Name) and target.id == "RELEASE_NOTES_FA":
                value_node = node.value
        if value_node is not None:
            break
    if value_node is None:
        return {}
    try:
        raw = ast.literal_eval(value_node)
    except (ValueError, TypeError, SyntaxError):
        return {}
    if not isinstance(raw, dict):
        return {}
    out: dict[str, list[str]] = {}
    for k, v in raw.items():
        key = str(k).strip().lstrip("vV")
        if isinstance(v, (list, tuple)):
            notes = [str(x) for x in v if str(x).strip()]
            if notes:
                out[key] = notes
    return out


async def fetch_remote_release_notes(
    *,
    timeout: float = 4.0,
    force: bool = False,
    channel: str | None = None,
) -> dict[str, list[str]] | None:
    """Download RELEASE_NOTES_FA from the active update channel (cached)."""
    from app.services.update_channel import (
        channel_branch,
        github_release_notes_url,
    )

    ch = channel_branch(channel)
    now = time.monotonic()
    cached = _REMOTE_NOTES_CACHE.get("data")
    ttl = _REMOTE_NOTES_TTL_OK if _REMOTE_NOTES_CACHE.get("ok") else _REMOTE_NOTES_TTL_FAIL
    if (
        not force
        and isinstance(cached, dict)
        and _REMOTE_NOTES_CACHE.get("channel") == ch
        and (now - float(_REMOTE_NOTES_CACHE["at"])) < ttl
    ):
        return dict(cached)

    try:
        async with httpx.AsyncClient(timeout=timeout, follow_redirects=True) as client:
            resp = await client.get(
                github_release_notes_url(channel=ch),
                headers={
                    "User-Agent": "PGClockBot-Panel",
                    "Cache-Control": "no-cache",
                    "Pragma": "no-cache",
                },
                params={"_": str(int(time.time()))} if force else None,
            )
            if resp.status_code != 200:
                raise RuntimeError(f"status {resp.status_code}")
            parsed = parse_release_notes_source(resp.text or "")
            if not parsed:
                raise RuntimeError("empty release notes")
            _REMOTE_NOTES_CACHE.update(
                {"at": now, "data": dict(parsed), "ok": True, "channel": ch}
            )
            return dict(parsed)
    except Exception as e:
        logger.debug("remote release notes fetch failed (%s): %s", ch, e)
        _REMOTE_NOTES_CACHE.update(
            {
                "at": now,
                "data": cached if isinstance(cached, dict) else None,
                "ok": False,
                "channel": ch,
            }
        )
        return dict(cached) if isinstance(cached, dict) else None


def _merge_notes_tables(
    remote_notes: dict[str, list[str]] | None = None,
) -> dict[str, list[str]]:
    """Local notes plus remote overlay (remote wins for the same version)."""
    table: dict[str, list[str]] = {
        str(k).strip().lstrip("vV"): list(v)
        for k, v in RELEASE_NOTES_FA.items()
        if v
    }
    if remote_notes:
        for k, v in remote_notes.items():
            key = str(k).strip().lstrip("vV")
            notes = [str(x) for x in (v or []) if str(x).strip()]
            if notes:
                table[key] = notes
    return table


def _versions_after_through(
    *,
    local: str,
    remote: str,
    table: dict[str, list[str]],
) -> list[str]:
    """Versions strictly newer than local and <= remote, newest first."""
    local_v = local.strip().lstrip("vV")
    remote_v = remote.strip().lstrip("vV")
    found: list[str] = []
    for ver in table:
        if is_newer(ver, local_v) and not is_newer(ver, remote_v):
            found.append(ver)
    found.sort(key=_parse_ver, reverse=True)
    return found


def changelog_for_update_page(
    *,
    local: str | None = None,
    remote: str | None = None,
    remote_notes: dict[str, list[str]] | None = None,
) -> dict:
    """Changelog from versions after *local* through *remote* (inclusive), newest first."""
    local = (local or local_version() or "").strip()
    remote = (remote or "").strip() or None
    upgrading = bool(remote and is_newer(remote, local))
    table = _merge_notes_tables(remote_notes)

    if upgrading:
        remote_v = remote.lstrip("vV")
        local_v = local.lstrip("vV")
        versions = _versions_after_through(local=local_v, remote=remote_v, table=table)
        blocks: list[dict[str, object]] = []
        for ver in versions:
            notes = list(table.get(ver) or [])
            if notes:
                blocks.append({"version": ver, "notes": notes})
        if not blocks:
            blocks = [{
                "version": remote_v,
                "notes": ["جزئیات این نسخه پس از دریافت از گیت‌هاب نمایش داده می‌شود."],
            }]
        if len(blocks) == 1:
            title = f"تغییرات نسخه {blocks[0]['version']}"
        else:
            title = f"تغییرات از {local_v} تا {remote_v}"
    else:
        ver = local.lstrip("vV")
        notes = notes_for_version(ver, table)
        block = {"version": ver, "notes": notes} if notes else latest_notes_block(table)
        blocks = [block] if block else []
        title = f"تغییرات نسخه {block['version']}" if block else "چنج‌لاگ"

    return {"title": title, "blocks": blocks, "has_notes": bool(blocks)}
